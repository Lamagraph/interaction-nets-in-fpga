#!/bin/sh
# Purpose: Generate a Mermaid module-dependency graph from `import` lines in src/.
# Usage:   agent-scripts/gen-module-graph.sh [source-dir] \
#            > lamagraph-core/docs/module-graph.generated.md
# Default source-dir: src (relative to the package root, i.e. lamagraph-core/).
#
# Edge semantics: `A --> B` means module A is imported by module B.
# Only project-internal imports (Core.*, INet.*) are included.

set -eu

SRC="${1:-src}"

echo "<!-- GENERATED by agent-scripts/gen-module-graph.sh — do not edit by hand -->"
echo
echo '```mermaid'
echo 'flowchart TD'
find "$SRC" -name '*.hs' | sort | while read -r file; do
	mod=$(printf '%s' "$file" | sed -e "s|^$SRC/||" -e 's|\.hs$||' -e 's|/|.|g')
	sed -n 's/^import[[:space:]]\{1,\}\(qualified[[:space:]]\{1,\}\)\{0,1\}\(\(Core\|INet\)\.[A-Za-z0-9_.]*\).*/\2/p' "$file" |
		while read -r imp; do
			printf '    %s --> %s\n' "$imp" "$mod"
		done
done
echo '```'
